#!/usr/bin/env python3
"""Ukrainian text for NFSU2: work/loc translations -> tools/loc_nfsu2/uk.tsv (HASH<TAB>UA, our text only)
-> community/src/text_uk.inc (cp1251, the game's byte for (TM)), plus the static checks.

usage: build_uk.py            (needs work/loc/{en.tsv,uniq_index.tsv,uk_*.tsv})
       build_uk.py --inc-only (uk.tsv -> text_uk.inc, no EN data needed)

Byte map: Cyrillic in cp1251 (the port's UA fonts draw Cyrillic in those slots, font_uk.m);
'—' and '…' become '-' and '...' (the game's own 0x83/0x86 bytes have no glyph in every font),
'™' becomes the game's 0x82; І і Ч « become A2 A3 A7 B5 (see REMAP)."""
import glob, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
LOC = os.path.join(ROOT, 'work', 'loc')
TSV = os.path.join(ROOT, 'tools', 'loc_nfsu2', 'uk.tsv')
INC = os.path.join(ROOT, 'community', 'src', 'text_uk.inc')
CYR = 'АБВГҐДЕЄЖЗИІЇЙКЛМНОПРСТУФХЦЧШЩЬЮЯабвгґдеєжзиіїйклмнопрстуфхцчшщьюя'
# Glyphs every UA text font must have (font_uk.m draws or keeps these): ASCII + Cyrillic + these.
EXTRA = '«»®©'
# Letters whose cp1251 byte the late-patched dialog font (tt21i) has no slot for: written as
# bytes it has and the text never uses (font_uk.m cp1251() maps them back).
REMAP = {'І': 0xA2, 'і': 0xA3, 'Ч': 0xA7, '«': 0xB5}


# The port's own option labels (text_patch.c s_always), Ukrainian.
ALWAYS = {
    0x8FE9288E: 'Відбиття на авто', 0x4AC50BCF: 'Масштаб роздільності',
    0x4CD775AC: 'Згладжування', 0x4E57D355: 'Анізотропія', 0xA9C27DFD: 'Квадратні пікселі',
    0x5CF08EB7: 'Вібрація',
}


def unesc(s):
    return s.replace('\\n', '\n').replace('\\t', '\t').replace('\\\\', '\\')


def esc(s):
    return s.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t')


def to_game(u):
    u = u.replace('—', '-').replace('…', '...').replace('’', "'")
    out = bytearray()
    for ch in u:
        if ch == '™':
            out.append(0x82)
        elif ch in REMAP:
            out.append(REMAP[ch])
        else:
            out += ch.encode('cp1251')
    return bytes(out)


def build_tsv():
    en = []
    for l in open(os.path.join(LOC, 'en.tsv'), encoding='utf-8'):
        p = l.rstrip('\n').split('\t', 2)
        en.append((p[0], p[1], unesc(p[2])))
    idx = {}
    for l in open(os.path.join(LOC, 'uniq_index.tsv'), encoding='utf-8'):
        k, t = l.rstrip('\n').split('\t', 1)
        idx[unesc(t)] = k
    uk = {}
    for f in sorted(glob.glob(os.path.join(LOC, 'uk_*.tsv'))):
        for l in open(f, encoding='utf-8'):
            l = l.rstrip('\n')
            if l:
                k, t = l.split('\t', 1)
                uk[k] = unesc(t)
    rows, missing, same = [], [], []
    for h, lab, t in en:
        k = idx.get(t)
        if k is None or k not in uk:
            missing.append((h, lab, t))
            continue
        u = uk[k]
        rows.append((h, u))
        if u == t and re.search('[a-z]{3}', t):
            same.append((h, lab, t))
    with open(TSV, 'w', encoding='utf-8') as f:
        f.write('# NFSU2 Ukrainian text (Deadware translation): label hash<TAB>text\n')
        for h, u in rows:
            f.write('%s\t%s\n' % (h, esc(u)))
    print('uk.tsv: %d of %d strings; no translation: %d; same as EN with lowercase words: %d'
          % (len(rows), len(en), len(missing), len(same)))
    for h, lab, t in missing[:10]:
        print('  missing', h, lab, repr(t[:60]))
    for h, lab, t in same[:40]:
        print('  same', h, lab, repr(t[:60]))
    return len(missing)


def build_inc():
    rows = []
    for l in open(TSV, encoding='utf-8'):
        if l.startswith('#') or not l.strip():
            continue
        h, u = l.rstrip('\n').split('\t', 1)
        rows.append((int(h, 16), unesc(u)))
    rows.sort()
    allowed = set(chr(c) for c in range(32, 127)) | set(CYR) | set(EXTRA) | set('—…’™\n')
    bad = [(h, c) for h, u in rows for c in u if c not in allowed]
    glyphs = sorted({b for _, u in rows for b in to_game(u) if b >= 0x80})
    with open(INC, 'w', encoding='ascii') as f:
        f.write('/* Generated by tools/loc_nfsu2/build_uk.py from tools/loc_nfsu2/uk.tsv; do not edit. */\n')
        f.write('static const struct { uint32_t hash; const char *text; } s_uk[] = {\n')
        for h, u in rows:
            b = to_game(u)
            s = ''.join(chr(c) if 32 <= c < 127 and c not in (34, 92, 63) else '\\%03o' % c for c in b)
            f.write('    { 0x%08Xu, "%s" },\n' % (h, s))
        f.write('};\n')
        f.write('static const struct { uint32_t hash; const char *text; } s_uk_always[] = {\n')
        for h, u in sorted(ALWAYS.items()):
            f.write('    { 0x%08Xu, "%s" },\n' % (h, ''.join('\\%03o' % c if c >= 127 else chr(c) for c in to_game(u))))
        f.write('};\n')
    print('text_uk.inc: %d strings; chars outside the UA glyph set: %d; bytes >= 0x80 used: %s'
          % (len(rows), len(bad), ' '.join('%02X' % b for b in glyphs)))
    for h, c in bad[:10]:
        print('  bad char %08X %r' % (h, c))
    return len(bad)


if __name__ == '__main__':
    n = 0 if '--inc-only' in sys.argv else build_tsv()
    n += build_inc()
    sys.exit(1 if n else 0)
